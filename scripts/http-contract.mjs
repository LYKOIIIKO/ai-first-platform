import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const apiDirectory = fileURLToPath(new URL('../apps/api/', import.meta.url));
const document = execFileSync(process.execPath, ['--import', 'tsx', 'src/transport/health/export-openapi.ts'], {
  cwd: apiDirectory,
  encoding: 'utf8',
});
const types = '// Generated by pnpm contract:generate.\n' + astToString(await openapiTS(JSON.parse(document)));
const artifacts = [
  ['apps/api/openapi.json', document],
  ['apps/web/src/shared/api/schema.gen.ts', types],
];
const check = process.argv.includes('--check');

for (const [path, content] of artifacts) {
  const url = new URL(`../${path}`, import.meta.url);
  if (!check) {
    writeFileSync(url, content);
  } else if (readFileSync(url, 'utf8').replaceAll('\r\n', '\n') !== content) {
    console.error(`${path} устарел. Выполните pnpm contract:generate.`);
    process.exitCode = 1;
  }
}
